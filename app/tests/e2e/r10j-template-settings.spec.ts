  await page.getByLabel('选择项目模板', { exact: true }).click()
  await page.getByRole('button', { name: '管理项目模板', exact: true }).click()
  const settings = page.getByRole('region', { name: '项目模板管理' })
  await expect(settings).toBeVisible()
  await settings.getByLabel('编辑项目模板', { exact: true }).selectOption('template-ai-tutorial')
  await settings.getByLabel('模板名称', { exact: true }).fill('AI产品短视频')
  await settings.getByRole('group', { name: '模板适用视频形式' }).getByRole('button', { name: '短视频', exact: true }).click()
  await settings.getByRole('group', { name: '模板适用项目类型' }).getByRole('button', { name: '普通', exact: true }).click()
  await settings.getByRole('group', { name: '模板默认阶段' }).getByLabel('拍摄', { exact: true }).uncheck()
  await settings.getByRole('button', { name: '保存模板', exact: true }).click()
