test('explicit toolbar, format shortcuts, save persistence and modal shortcut isolation', async ({ browserName }, info) => {
  expect(browserName).toBe('chromium')
  const editor = page.getByRole('textbox', { name: '复盘正文', exact: true })
  const toolbar = editor.locator('xpath=ancestor::div[contains(@class,"review-rich-editor")]').locator('.script-format-toolbar')
  await expect(toolbar).toBeHidden()
  await editor.fill('快捷键复盘')
  await expect(toolbar).toBeHidden()
  await editor.press('Meta+a')
  for (const key of ['Meta+b', 'Meta+i', 'Meta+u', 'Meta+Shift+s', 'Meta+Shift+h']) await editor.press(key)
  await expect(editor.locator('strong')).toHaveText('快捷键复盘')
  await expect(editor.locator('em')).toHaveText('快捷键复盘')
  await expect(editor.locator('u')).toHaveText('快捷键复盘')
  await expect(editor.locator('s')).toHaveText('快捷键复盘')
  await expect(editor.locator('mark')).toHaveAttribute('data-color', '#F3D9A3')
  expect(await page.evaluate(async q => (await (globalThis as Globals).creatorOS.getPersonalReview(q)).period.revision, query)).toBe(0)
  await editor.press('Meta+z')
  await expect(editor.locator('mark')).toHaveCount(0)
  await editor.press('Meta+Shift+z')
  await expect(editor.locator('mark')).toHaveCount(1)
  await editor.locator('xpath=ancestor::div[contains(@class,"review-rich-editor")]').getByRole('button', { name: '展开样式面板' }).click()
  await expect(toolbar).toBeVisible()
  await page.getByRole('button', { name: '二级标题', exact: true }).click()
  await expect(editor.locator('h2')).toHaveText('快捷键复盘')
  await editor.locator('h2').click()
  await expect(page.getByRole('button', { name: '二级标题', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await editor.press('Meta+Alt+3')
  await expect(editor.locator('h3')).toHaveText('快捷键复盘')
  await editor.press('Meta+Alt+2')
  await page.screenshot({ path: info.outputPath('review-editor-active.png') })
  await editor.press('Meta+s')
  await expect(page.getByRole('button', { name: '已保存', exact: true })).toBeDisabled()
  await page.reload()
  await expect(editor.locator('h2')).toHaveText('快捷键复盘')
  await expect(editor.locator('mark')).toHaveAttribute('data-color', '#F3D9A3')
  await expect(toolbar).toBeHidden()
  await editor.focus()
  await expect(toolbar).toBeHidden()
  await editor.press('Meta+Shift+m')
  await expect(toolbar).toBeVisible()
  await page.getByRole('button', { name: '加粗', exact: true }).focus()
  await expect(toolbar).toBeVisible()
  await page.getByRole('heading', { name: '自由复盘', exact: true }).click()
  await expect(toolbar).toBeVisible()
  await page.getByRole('button', { name: '收起样式面板' }).click()
  await expect(toolbar).toBeHidden()
  const revision = await page.evaluate(async q => (await (globalThis as Globals).creatorOS.getPersonalReview(q)).period.revision, query)
  await page.getByRole('button', { name: '添加经验', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '编辑经验', exact: true }), body = dialog.getByRole('textbox', { name: '记录正文', exact: true })
  await expect(dialog.getByRole('toolbar')).toBeHidden()
  await dialog.getByLabel('记录标题').fill('快捷键经验')
  await body.fill('独立保存')
  await expect(dialog.getByRole('toolbar')).toBeHidden()
  await body.press('Meta+a')
  await body.press('Meta+b')
  await expect(body.locator('strong')).toHaveText('独立保存')
  await body.press('Meta+s')
  await expect.poll(() => page.evaluate(async () => (await (globalThis as Globals).creatorOS.searchReviewEntries('快捷键经验')).length)).toBe(1)
  await expect(dialog).toBeVisible()
  expect(await page.evaluate(async q => (await (globalThis as Globals).creatorOS.getPersonalReview(q)).period.revision, query)).toBe(revision)
  await dialog.getByLabel('记录标题').click()
  await expect(dialog.getByRole('toolbar')).toBeHidden()
})
