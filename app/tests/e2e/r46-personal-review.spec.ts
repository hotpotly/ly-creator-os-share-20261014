test('save conflicts preserve draft; invalid files fail without losing the text', async ({ browserName }, info) => {
  expect(browserName).toBe('chromium')
  await page.getByRole('textbox', { name: '复盘正文', exact: true }).fill('我的未保存草稿')
  await page.evaluate(async () => { const api = (globalThis as Globals).creatorOS; const data = await api.getPersonalReview({ kind: 'monthly', anchor: '2026-09-27' }); await api.savePersonalReview({ ...data.period, targetMinutes: 600 }) })
  await page.getByRole('button', { name: '保存复盘', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('其他窗口更新')
  await expect(page.getByRole('textbox', { name: '复盘正文', exact: true })).toContainText('我的未保存草稿')
  await page.getByRole('button', { name: '放弃草稿并加载已保存版本' }).click()
  const editor = page.getByRole('textbox', { name: '生活记录新内容', exact: true })
  await editor.fill('无效图片不能覆盖文字')
  await editor.press('Meta+s')
  await page.getByRole('button', { name: '更多无效图片不能覆盖文字', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '编辑生活记录' })
  const badPath = info.outputPath('bad.png'); mkdirSync(info.outputPath(), { recursive: true }); writeFileSync(badPath, '<svg onload="alert(1)"></svg>')
  await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [path], bookmarks: [] })) as typeof dialog.showOpenDialog }, badPath)
  await dialog.getByRole('button', { name: '保存文字并添加图片' }).click()
  await expect(dialog.getByRole('alert')).toContainText('无法读取')
  await expect(dialog.getByLabel('记录标题')).toHaveValue('无效图片不能覆盖文字')
})
