import { _electron as electron, expect, test, type ElectronApplication, type Page } from '@playwright/test'
import { join } from 'node:path'
import type { CreatorOSApi } from '../../src/shared/ipc'
type Globals = typeof globalThis & { creatorOS: CreatorOSApi }
let app: ElectronApplication, page: Page
test.beforeEach(async ({ browserName }, info) => {
  expect(browserName).toBe('chromium')
  app = await electron.launch({ args: ['.'], cwd: join(import.meta.dirname, '../..'), env: { ...process.env, NODE_ENV: 'test', CREATOR_OS_TEST_DATE: '2026-09-27', CREATOR_OS_TEST_BACKGROUND: '1', CREATOR_OS_USER_DATA: info.outputPath('user-data') } })
  page = await app.firstWindow()
  await expect.poll(() => page.evaluate(async () => (await (globalThis as Globals).creatorOS.getWorkspace()).today)).toBe('2026-09-27')
  await page.evaluate(async () => {
    const api = (globalThis as Globals).creatorOS
    await api.setDailyWorkLogTotal('2026-09-21', 150, await api.getDailyWorkLog('2026-09-21'))
    await api.createTodoBatch([{ title: '当天剪辑', category: 'self_media', suggestedCategory: 'self_media', plannedDate: '2026-09-21', segment: 'morning', projectId: null, stageKey: null, trackingMode: 'checklist', progress: 0 }])
    location.hash = '#/reviews?kind=weekly&anchor=2026-09-27'
  })
  await expect(page.getByRole('group', { name: '每日工作投入' })).toBeVisible()
})
test.afterEach(async () => { await app?.close() })
test('chart opens the exact day; shared editors update hours, todos and travel and feed weekly/monthly totals', async () => {
  await page.locator('.review-chart-points button[data-day="2026-09-21"]').click()
  await expect(page).toHaveURL(/view=daily/)
  const daily = page.locator('.review-daily')
  await expect(daily.locator('.todo-work-log')).toContainText('2小时30分钟')
  await daily.getByRole('button', { name: '记录', exact: true }).click()
  const hours = page.getByRole('dialog', { name: '记录2026/09/21投入', exact: true })
  await hours.getByLabel('总时长').fill('4.25')
  await hours.getByRole('button', { name: '保存', exact: true }).click()
  await expect(daily.locator('.todo-work-log')).toContainText('4小时15分钟')
  await daily.getByRole('button', { name: '完成当天剪辑', exact: true }).click()
  await expect(daily.getByRole('button', { name: '重新打开当天剪辑', exact: true })).toBeVisible()
  await daily.locator('.todo-title-link').click()
  await daily.getByLabel('修改待办文字').fill('当天剪辑已修改')
  await daily.getByLabel('修改待办文字').press('Enter')
  await expect(daily.getByRole('button', { name: '重新打开当天剪辑已修改', exact: true })).toBeVisible()
  await daily.getByRole('button', { name: '安排行程', exact: true }).click()
  await page.getByRole('group', { name: '行程类型' }).getByRole('button', { name: '休息', exact: true }).click()
  await page.getByRole('button', { name: '保存休息', exact: true }).click()
  await expect(daily.locator('.business-trip-summary')).toContainText('休息记录')
  await page.getByRole('button', { name: '周复盘', exact: true }).click()
  const bar = page.locator('.review-chart-points button[data-day="2026-09-21"]')
  await expect(bar).toHaveAttribute('data-travel-kind', 'rest')
  await bar.hover()
  await expect(page.getByLabel('每日工时读数')).toContainText('4小时15分钟')
  await page.getByRole('button', { name: '月复盘', exact: true }).click()
  await expect(page.locator('.review-hour-number strong')).toHaveText('4.3')
  await page.reload()
  await expect(page.locator('.review-hour-number strong')).toHaveText('4.3')
  await expect(page.locator('.review-schedule')).toHaveAttribute('open', '')
  await page.getByRole('button', { name: '查看2026-09-21记录', exact: true }).click()
  await expect(daily.getByRole('button', { name: '重新打开当天剪辑已修改', exact: true })).toBeVisible()
})
test('missing days are editable; date navigation and daily text remain same-source; period draft survives', async ({ browserName }, info) => {
  expect(browserName).toBe('chromium')
  await page.getByRole('textbox', { name: '复盘正文', exact: true }).fill('未保存周草稿')
  await page.getByRole('button', { name: '每日记录', exact: true }).click()
  await expect(page.locator('.review-daily .todo-work-log')).toHaveAttribute('data-day', '2026-09-27')
  await page.getByRole('button', { name: '查看前一天待办', exact: true }).click()
  await expect(page).toHaveURL(/anchor=2026-09-26/)
  await page.reload()
  await expect(page.locator('.review-daily .todo-work-log')).toHaveAttribute('data-day', '2026-09-26')
  await page.locator('.review-daily').getByRole('button', { name: '记录', exact: true }).click()
  await page.getByRole('dialog').getByLabel('总时长').fill('1.5')
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  const editor = page.getByRole('textbox', { name: '生活记录新内容', exact: true })
  await editor.fill('当天散步\n散步后整理思路')
  await editor.press('Meta+s')
  await expect(page.locator('.review-inline-title')).toHaveValue('当天散步')
  await expect(page.locator('.review-inline-meta input[type="date"]')).toHaveValue('2026-09-26')
  for (const width of [680, 1280]) {
    await app.evaluate(({ BrowserWindow }, width) => BrowserWindow.getAllWindows()[0]!.setContentSize(width, 900), width)
    for (const theme of ['light', 'dark']) {
      await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
      await expect.poll(() => page.locator('.review-page').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    }
  }
  await page.screenshot({ path: info.outputPath('daily-records.png') })
  await page.getByRole('button', { name: '查看后一天待办', exact: true }).click()
  await expect(page.locator('.review-inline-record[data-review-entry]')).toHaveCount(0)
  await page.getByRole('button', { name: '周复盘', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '复盘正文', exact: true })).toHaveText('未保存周草稿')
  await expect(page.locator('.review-hour-number strong')).toHaveText('4')
  await expect(page.locator('.review-inline-title')).toHaveValue('当天散步')
  await page.locator('.review-chart-points button[data-day="2026-09-26"]').focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.review-daily .todo-work-log')).toHaveAttribute('data-day', '2026-09-26')
})
